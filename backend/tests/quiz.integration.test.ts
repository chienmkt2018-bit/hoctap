import assert from 'node:assert/strict';
import type { AddressInfo } from 'node:net';
import test from 'node:test';
import mongoose from 'mongoose';
import { MongoMemoryReplSet } from 'mongodb-memory-server';
import { createAccessToken } from '../src/auth.js';

const jwtSecret = 'integration-test-only-secret-with-at-least-32-bytes';

type AttemptPayload = {
  attemptId: string;
  answers: Array<{ questionId: string; selectedOptionId: string }>;
};

const perfectAnswers = [
  { questionId: 'q1', selectedOptionId: '1' },
  { questionId: 'q2', selectedOptionId: '0' },
  { questionId: 'q3', selectedOptionId: '2' },
];

async function submitAttempt(
  baseUrl: string,
  token: string | undefined,
  quizId: number,
  payload: AttemptPayload,
): Promise<Response> {
  return fetch(`${baseUrl}/api/v1/quizzes/${quizId}/attempts`, {
    method: 'POST',
    headers: {
      'content-type': 'application/json',
      ...(token ? { authorization: `Bearer ${token}` } : {}),
    },
    body: JSON.stringify(payload),
  });
}

async function readProgress(baseUrl: string, token: string) {
  const response = await fetch(`${baseUrl}/api/v1/progress`, {
    headers: { authorization: `Bearer ${token}` },
  });
  assert.equal(response.status, 200);
  return response.json() as Promise<{ progress: { totalXp: number; completedLessonIds: number[] } }>;
}

test('quiz API idempotency persists correctly in an isolated MongoDB replica set', { timeout: 120_000 }, async (t) => {
  const previousMongoUri = process.env.MONGODB_URI;
  const previousJwtSecret = process.env.JWT_SECRET;
  const replicaSet = await MongoMemoryReplSet.create({
    replSet: { count: 1, storageEngine: 'wiredTiger' },
  });

  let httpServer: ReturnType<(typeof import('node:http'))['createServer']> | undefined;

  try {
    // This URI is generated by mongodb-memory-server; no shared or production DB is used.
    const mongoUri = replicaSet.getUri('hoctap_integration_test');
    process.env.MONGODB_URI = mongoUri;
    process.env.JWT_SECRET = jwtSecret;
    await mongoose.connect(mongoUri);

    const [{ app }, { QuizAttemptModel }] = await Promise.all([
      import('../src/server.js'),
      import('../src/models/QuizAttempt.js'),
    ]);

    httpServer = app.listen(0);
    await new Promise<void>((resolve, reject) => {
      httpServer?.once('listening', resolve);
      httpServer?.once('error', reject);
    });
    const address = httpServer.address() as AddressInfo;
    const baseUrl = `http://127.0.0.1:${address.port}`;

    const learnerA = 'integration-learner-a';
    const learnerB = 'integration-learner-b';
    const tokenA = createAccessToken(learnerA, jwtSecret);
    const tokenB = createAccessToken(learnerB, jwtSecret);
    const originalPayload: AttemptPayload = {
      attemptId: 'attempt_integration_0001',
      answers: perfectAnswers,
    };

    await t.test('rejects a quiz submission without authentication', async () => {
      const response = await submitAttempt(baseUrl, undefined, 1, originalPayload);
      assert.equal(response.status, 401);
      assert.equal((await response.json() as { error: { code: string } }).error.code, 'UNAUTHORIZED');
    });

    await t.test('creates the attempt and persists the first XP award', async () => {
      const response = await submitAttempt(baseUrl, tokenA, 1, originalPayload);
      assert.equal(response.status, 201);
      const body = await response.json() as {
        attemptId: string;
        correctCount: number;
        xpAwarded: number;
        totalXp: number;
        replayed: boolean;
      };

      assert.equal(body.attemptId, originalPayload.attemptId);
      assert.equal(body.correctCount, 3);
      assert.equal(body.xpAwarded, 30);
      assert.equal(body.totalXp, 30);
      assert.equal(body.replayed, false);

      const progress = await readProgress(baseUrl, tokenA);
      assert.equal(progress.progress.totalXp, 30);
      assert.deepEqual(progress.progress.completedLessonIds, [1]);
      assert.equal(await QuizAttemptModel.countDocuments({ learnerId: learnerA }), 1);
    });

    await t.test('replays an identical attempt without awarding XP twice', async () => {
      const response = await submitAttempt(baseUrl, tokenA, 1, originalPayload);
      assert.equal(response.status, 200);
      const body = await response.json() as { replayed: boolean; xpAwarded: number; totalXp: number };

      assert.equal(body.replayed, true);
      assert.equal(body.xpAwarded, 30);
      assert.equal(body.totalXp, 30);
      assert.equal((await readProgress(baseUrl, tokenA)).progress.totalXp, 30);
      assert.equal(await QuizAttemptModel.countDocuments({ learnerId: learnerA }), 1);
    });

    await t.test('returns 409 for changed answers and leaves persisted progress unchanged', async () => {
      const changedPayload: AttemptPayload = {
        ...originalPayload,
        answers: perfectAnswers.map((answer) =>
          answer.questionId === 'q2'
            ? { ...answer, selectedOptionId: '1' }
            : answer,
        ),
      };
      const response = await submitAttempt(baseUrl, tokenA, 1, changedPayload);
      assert.equal(response.status, 409);
      assert.equal((await response.json() as { error: { code: string } }).error.code, 'IDEMPOTENCY_KEY_REUSED');
      assert.equal((await readProgress(baseUrl, tokenA)).progress.totalXp, 30);
      assert.equal(await QuizAttemptModel.countDocuments({ learnerId: learnerA }), 1);
    });

    await t.test('returns 409 when the same attempt ID is reused for another quiz', async () => {
      const response = await submitAttempt(baseUrl, tokenA, 2, originalPayload);
      assert.equal(response.status, 409);
      assert.equal((await response.json() as { error: { code: string } }).error.code, 'IDEMPOTENCY_KEY_REUSED');
      assert.equal((await readProgress(baseUrl, tokenA)).progress.totalXp, 30);
      assert.equal(await QuizAttemptModel.countDocuments({ learnerId: learnerA }), 1);
    });

    await t.test('keeps attempts and XP isolated between learners', async () => {
      const response = await submitAttempt(baseUrl, tokenB, 1, originalPayload);
      assert.equal(response.status, 201);
      const body = await response.json() as { replayed: boolean; totalXp: number };
      assert.equal(body.replayed, false);
      assert.equal(body.totalXp, 30);

      assert.equal((await readProgress(baseUrl, tokenA)).progress.totalXp, 30);
      assert.equal((await readProgress(baseUrl, tokenB)).progress.totalXp, 30);
      assert.equal(await QuizAttemptModel.countDocuments({ learnerId: learnerA }), 1);
      assert.equal(await QuizAttemptModel.countDocuments({ learnerId: learnerB }), 1);
    });
  } finally {
    if (httpServer?.listening) {
      await new Promise<void>((resolve, reject) => {
        httpServer?.close((error) => error ? reject(error) : resolve());
      });
    }
    await mongoose.disconnect();
    await replicaSet.stop();
    if (previousMongoUri === undefined) delete process.env.MONGODB_URI;
    else process.env.MONGODB_URI = previousMongoUri;
    if (previousJwtSecret === undefined) delete process.env.JWT_SECRET;
    else process.env.JWT_SECRET = previousJwtSecret;
  }
});
